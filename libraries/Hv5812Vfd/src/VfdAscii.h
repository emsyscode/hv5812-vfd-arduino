// Out-of-range characters render as '?'. Bit 0 is always clear.
static inline uint8_t ascii_5x7_column(uint8_t ch, uint8_t column) {
    if (column >= 5) return 0;
    if (ch < 32 || ch > 126) ch = '?';
#ifdef __AVR__
    return pgm_read_byte(&ascii_5x7[ch - 32][column]);
#else
    return ascii_5x7[ch - 32][column];
#endif
}
